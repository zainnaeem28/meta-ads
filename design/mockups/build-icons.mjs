// Inlines the vendored Lucide SVGs (assets/icons/*.svg) into assets/icons.js as window.ICONS = { name: '<svg…>' }.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const icons = {};
for (const f of readdirSync('assets/icons').filter((n) => n.endsWith('.svg'))) {
  const raw = readFileSync(`assets/icons/${f}`, 'utf8');
  const inner = raw.replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[\s\S]*?>/, '').replace('</svg>', '').replace(/\s+/g, ' ').trim();
  icons[f.replace('.svg', '')] = inner;
}
writeFileSync('assets/icons.js', `// Generated by build-icons.mjs from Lucide ${process.argv[2] ?? ''} (ISC). Do not edit.\nwindow.ICONS = ${JSON.stringify(icons)};\n`);
console.log(Object.keys(icons).length, 'icons');
